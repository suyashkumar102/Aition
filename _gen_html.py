w('  const btn = document.getElementById("btn-confirm-debias");')
w('  btn.disabled = true;')
w('  btn.textContent = "Running debiasing...";')
w('  try {')
w('    const res = await fetch(`http://localhost:8000/audit/${auditId}/debias`, {')
w('      method: "POST",')
w('      headers: { "Content-Type": "application/json" },')
