# ── JAVASCRIPT ────────────────────────────────────────────────────
w('<script>')
w('let auditId = null;')
w('let selectedDefinition = "demographic_parity";')
w('')
w('// ── Utility ──────────────────────────────────────────────────')
w('function showError(msg) {')
w('  const b = document.getElementById("error-box");')
w('  b.textContent = msg; b.style.display = "block";')
w('}')
w('function hideError() { document.getElementById("error-box").style.display = "none"; }')
w('function biasIndexClass(v) {')
w('  if (v < 0.2) return "badge-bias-green";')
w('  if (v < 0.5) return "badge-bias-amber";')
w('  return "badge-bias-red";')
w('}')
w('')
w('// ── Run Audit ────────────────────────────────────────────────')
w('async function runAudit(file) {')
w('  hideError();')
w('  document.getElementById("results").style.display = "none";')
w('  document.getElementById("impossibility-section").style.display = "none";')
w('  document.getElementById("debiasing-section").style.display = "none";')
w('  document.getElementById("report-section").style.display = "none";')
w('  document.getElementById("loading").style.display = "block";')
w('  try {')
w('    const fd = new FormData();')
w('    if (file) fd.append("file", file);')
w('    const res = await fetch("http://localhost:8000/audit", { method: "POST", body: fd });')
w('    if (!res.ok) { const e = await res.json(); throw new Error(`HTTP ${res.status}: ${e.detail || e.error}`); }')
w('    const data = await res.json();')
w('    auditId = data.audit_id;')
w('    renderResults(data);')
w('  } catch(e) { showError(e.message); }')
w('  finally { document.getElementById("loading").style.display = "none"; }')
w('}')
w('')
w('// ── Render Results ───────────────────────────────────────────')
w('function renderResults(data) {')
w('  const s = data.standard_audit;')
w('  const c = data.causal_audit;')
w('  // Standard panel')
w('  document.getElementById("std-badge").innerHTML = `<span class="badge ${s.passes_standard_test ? "badge-fair" : "badge-biased"}">${s.verdict} ${s.passes_standard_test ? "✓" : "✗"}</span>`;')
w('  document.getElementById("std-dpd").textContent = s.demographic_parity_difference.toFixed(4);')
w('  const bi = data.bias_index;')
w('  document.getElementById("bias-index-badge").innerHTML = `<span class="badge ${biasIndexClass(bi)}">Bias Index: ${bi.toFixed(4)}</span>`;')
w('  // Causal panel')
w('  document.getElementById("causal-badge").innerHTML = `<span class="badge ${c.proxy_paths_found > 0 ? "badge-proxy" : "badge-no-proxy"}">${c.verdict}</span>`;')
w('  document.getElementById("causal-paths").textContent = c.proxy_paths_found;')
w('  const pl = document.getElementById("proxy-list"); pl.innerHTML = "";')
w('  c.paths.forEach(p => {')
w('    const li = document.createElement("li");')
w('    li.innerHTML = `<strong>${p.path.join(" → ")}</strong> — effect: ${p.effect.toFixed(3)}`;')
w('    pl.appendChild(li);')
w('  });')
w('  document.getElementById("affected-count").innerHTML = `<strong>${c.affected_candidates}</strong> candidates affected by proxy discrimination`;')
w('  // Graph')
w('  renderGraph(data.graph_data);')
w('  // Report')
w('  document.getElementById("report-text").innerHTML = marked.parse(data.plain_language_report || "");')
w('  document.getElementById("report-section").style.display = "block";')
w('  document.getElementById("results").style.display = "block";')
w('  // Impossibility slider')
w('  if (data.impossibility_surface) initImpossibilitySlider(data.impossibility_surface);')
w('}')
w('')
w('// ── Impossibility Slider ─────────────────────────────────────')
w('function initImpossibilitySlider(surface) {')
w('  const slider = document.getElementById("impossibility-slider");')
w('  const points = surface.frontier_points;')
w('  const accuracies = surface.accuracy_at_threshold;')
w('  const maxDP = Math.max(...points.map(p => p[0])) || 0.3;')
w('  const maxEO = Math.max(...points.map(p => p[1])) || 0.3;')
w('  function update() {')
w('    const idx = Math.round(slider.value * (points.length - 1) / 100);')
w('    const [dpd, eod] = points[idx];')
w('    const acc = accuracies[idx];')
w('    document.getElementById("dp-value").textContent = dpd.toFixed(3);')
w('    document.getElementById("eo-value").textContent = eod.toFixed(3);')
w('    document.getElementById("accuracy-value").textContent = (acc * 100).toFixed(1) + "%";')
w('    document.getElementById("dp-bar").style.width = Math.min(100, (dpd / maxDP) * 100) + "%";')
w('    document.getElementById("eo-bar").style.width = Math.min(100, (eod / maxEO) * 100) + "%";')
w('    document.getElementById("acc-bar").style.width = (acc * 100) + "%";')
w('    const cost = ((accuracies[0] - acc) * 100).toFixed(1);')
w('    const pos = slider.value > 50 ? "Equalized Odds" : "Demographic Parity";')
w('    selectedDefinition = slider.value > 50 ? "equalized_odds" : "demographic_parity";')
w('    document.getElementById("btn-confirm-debias").textContent = `Confirm: Apply ${pos} →`;')
w('    document.getElementById("slider-explanation").textContent =')
w('      `Moving toward Equalized Odds costs ${cost}% accuracy but reduces error rate disparity.`;')
w('  }')
w('  slider.addEventListener("input", update);')
w('  update();')
w('  document.getElementById("impossibility-section").style.display = "block";')
w('}')
w('')
